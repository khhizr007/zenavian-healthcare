// Lists every remaining TODO_CLIENT: value. Writes docs/CLIENT-TODO.md. Exit code 0 (warning only) unless --strict.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOTS = ['src', 'functions', 'wrangler.toml', 'public'];
const SKIP = /node_modules|dist|\.astro|\.(png|webp|woff2|pdf)$/;
const hits = [];

function walk(p) {
  if (SKIP.test(p)) return;
  const st = statSync(p);
  if (st.isDirectory()) return readdirSync(p).forEach((f) => walk(join(p, f)));
  readFileSync(p, 'utf8')
    .split(/\r?\n/)
    .forEach((line, i) => {
      const m = line.match(/TODO_CLIENT:([^'"`]*)/);
      if (m)
        hits.push({ file: relative('.', p).replaceAll('\\', '/'), line: i + 1, what: m[1].trim() });
    });
}
ROOTS.forEach((r) => {
  try {
    walk(r);
  } catch {
    /* optional path */
  }
});

const strict = process.argv.includes('--strict');
if (hits.length === 0) console.log('No TODO_CLIENT placeholders remain.');
else {
  console.warn(`\n::warning::${hits.length} TODO_CLIENT placeholder(s) remain:`);
  hits.forEach((h) => console.warn(`  ${h.file}:${h.line}  ${h.what}`));
}

const md = `# CLIENT-TODO

> Auto-generated by \`npm run check:placeholders\`. Do not edit by hand: change the source values and re-run.

## 1. Placeholders still in the code (${hits.length})

${hits.length ? hits.map((h) => `- [ ] **${h.what}**  \`${h.file}:${h.line}\``).join('\n') : '_None. All placeholder values have been supplied._'}

## 2. Assets and approvals needed from the client

- [ ] Final logo (SVG/PNG) to replace \`public/brand/logo.svg\` and \`public/brand/mark.svg\`
- [ ] Real product pack-shots: \`public/images/products/<slug>.webp\` (see docs/PHOTO-SHOTLIST.md)
- [ ] Farm, laboratory and packaging photos (see docs/PHOTO-SHOTLIST.md)
- [ ] **Approved label data per product**: composition, dosage, withdrawal period, pack sizes, dosage form, storage. Enter in \`src/content/products/<slug>.json\`. Until supplied, the site shows the label-reference text.
- [ ] Product sheets (PDF) per product if available (\`brochurePdf\` field)
- [ ] Client-designed catalogue PDF, if any (drop at \`public/downloads/override/catalogue.pdf\`)
- [ ] Certificates, only if genuinely held (\`site.certifications\`)
- [ ] Real statistics, only if genuinely wanted (\`site.stats\`)
- [ ] Founder message, founding year, team (\`site.about\`); sections stay hidden until supplied

## 3. Copy written by us that the client must review and approve

- [ ] Home page intro paragraphs and "Our Commitment" paragraph (the brief supplied only the opening words)
- [ ] About page (written only from facts in the brief)
- [ ] Poultry Healthcare Solutions page and FAQ (\`src/config/solutions.ts\`): ideally reviewed by a veterinarian
- [ ] Distributor page benefits list
- [ ] Privacy Policy, Terms, Disclaimer: **draft, needs legal counsel review**; confirm retention periods and jurisdiction
- [ ] Pillar and focus-area short descriptions on the home page

## 4. Accounts and services the owner must create (see docs/DEPLOY.md and docs/EMAIL-SETUP.md)

- [ ] Domain and Cloudflare account; Pages project connected to the Git repo
- [ ] Professional mailbox (info@domain) and Resend domain verification
- [ ] Cloudflare Turnstile widget (site key + secret)
- [ ] Cloudflare D1 database and migration
- [ ] Cloudflare Web Analytics token (cookieless)
- [ ] Google Search Console and Google Business Profile (see docs/SEO-LAUNCH.md)
`;
writeFileSync('docs/CLIENT-TODO.md', md);
if (strict && hits.length) process.exit(1);
